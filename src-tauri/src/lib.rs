use config::{loader, watcher, ConfigState};
use tauri::Emitter;

const BINDINGS_HEADER: &str = "// Auto-generated by tauri-specta — do not edit manually.\n\
     // Run `cargo run --bin generate-bindings` to regenerate.\n\n";

fn typescript_exporter() -> specta_typescript::Typescript {
    specta_typescript::Typescript::default().header(BINDINGS_HEADER)
}

/// Export TypeScript bindings from the typed command bridge.
pub fn export_bindings() {
    bridge::build_commands()
        .export(typescript_exporter(), "../src/lib/bridge/bindings.ts")
        .expect("Failed to export TypeScript bindings");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    env_logger::Builder::from_env(env_logger::Env::default().default_filter_or("info")).init();

    // Load config from XDG path (writes defaults on first run).
    let (initial_config, config_path) = match loader::load() {
        Ok(pair) => pair,
        Err(e) => {
            log::error!("fatal: cannot load config: {e:#}");
            std::process::exit(1);
        }
    };

    // File-watch channel: receives updated Config on each file save.
    let config_rx = watcher::spawn(config_path, initial_config.clone());
    let config_state = ConfigState::new(initial_config, config_rx.clone());

    let commands = bridge::build_commands();

    // In debug builds, regenerate the TS bindings so the committed copy stays current.
    #[cfg(debug_assertions)]
    commands
        .export(typescript_exporter(), "../src/lib/bridge/bindings.ts")
        .expect("Failed to export TypeScript bindings");

    let invoke_handler = commands.invoke_handler();

    let builder = tauri::Builder::default()
        .plugin(tauri_plugin_shell::init())
        .invoke_handler(invoke_handler)
        .manage(config_state.clone());

    // Install all self-registered plugins (services from other streams).
    // The launcher plugin is self-registered in launcher::plugin via inventory::submit!
    let builder = registry::setup(builder);

    builder
        .setup(move |app| {
            use tauri::Manager;
            // Keep the in-memory Config in sync with the file watcher.
            config_state.start_sync_loop();

            // Bridge watcher → frontend: emit "config-changed" on each reload.
            {
                let app_handle = app.handle().clone();
                let mut rx = config_rx.clone();
                tauri::async_runtime::spawn(async move {
                    while rx.changed().await.is_ok() {
                        let new_cfg = rx.borrow().clone();
                        app_handle.emit("config-changed", &new_cfg).ok();
                    }
                });
            }

            // Path A: apply layer-shell before the bar window is shown.
            #[cfg(target_os = "linux")]
            {
                let win = app
                    .get_webview_window("bar")
                    .expect("bar window defined in tauri.conf.json");

                let gtk_win = win.gtk_window().expect("failed to get GTK window for bar");
                let bar_config = layer_shell::SurfaceConfig::top_bar(36, "mantle-bar");
                layer_shell::LayerShellManager::apply_to_window(&gtk_win, &bar_config, None);
                win.show().expect("failed to show bar window");

                if let Some(launcher_win) = app.get_webview_window("launcher") {
                    launcher::setup_surface(&launcher_win)
                        .expect("Failed to apply layer shell to launcher window");
                }
            }

            // On non-Linux (dev/CI), show the window normally.
            #[cfg(not(target_os = "linux"))]
            {
                if let Some(win) = app.get_webview_window("bar") {
                    let _ = win.show();
                }
            }

            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running Mantle");
}

